  function route() {
    const h = location.hash.replace(/^#\//, '') || 'home';
    const [name, arg] = h.split('/');
    const fn = views[name] || views.home;
    stopTimer(); save();
    const view = $('#view');
    view.innerHTML = fn(arg);
    window.scrollTo(0, 0);
    $$('#nav a').forEach(a => {
      const r = a.dataset.route;
      a.classList.toggle('active', r === name || (r === 'course' && name === 'lesson') || (r === 'tests' && name === 'quiz'));
    });
    $('#sidebar').classList.remove('open');
    bind(name, arg);
    document.title = 'Информатика — окуу платформасы';
  }

  function bind(name, arg) {
    if (name === 'lesson') {
      if ($('#practCard')) bindPract(arg);
      $$('[data-check]').forEach(c => c.addEventListener('change', () => {
        const a = S.checks[arg] || (S.checks[arg] = []); a[+c.dataset.check] = c.checked; save();
      }));
      const nb = $('#noteBox'); let tm;
      nb.addEventListener('input', () => { S.notes[arg] = nb.value; clearTimeout(tm); tm = setTimeout(() => { save(); toast(t('saved')); }, 600); });
      $('#doneBtn').addEventListener('click', () => {
        S.done[arg] = !S.done[arg]; if (!S.done[arg]) delete S.done[arg]; save(); updateSide(); route();
        if (S.done[arg]) toast('✓ ' + t('done'));
      });
    }
    if (name === 'quiz') {
      renderQuiz();
    }
    if (name === 'grades') {
      renderGrade();
      $$('[data-g]').forEach(i => i.addEventListener('input', () => { S.grades[i.dataset.g] = i.value; save(); renderGrade(); }));
      $('#fillTk').addEventListener('click', () => {
        const sc = MODULES.map(m => bestScore(m.id)).filter(v => v !== null);
        if (!sc.length) { toast('Алгач тест тапшырыңыз'); return; }
        S.grades.tk = (sc.reduce((a, b) => a + b, 0) / sc.length * 0.4).toFixed(1); save(); route();
      });
      $('#resetG').addEventListener('click', () => { S.grades = Object.assign({}, def.grades); save(); route(); });
    }
  }

  function quizClick(e) {
    const b = e.target.closest('.opt');
    const nx = e.target.closest('[data-next]');
    if (b && quiz && !quiz.answered) {
      quiz.answered = true;
      const q = quiz.qs[quiz.i], k = +b.dataset.k, ok = q.o[k].ok;
      if (ok) quiz.score++;
      $$('.opt').forEach((o, i) => { o.disabled = true; if (q.o[i].ok) o.classList.add('right'); });
      if (!ok) b.classList.add('wrong');
      const last = quiz.i === quiz.qs.length - 1;
      $('#quizFb').innerHTML = `<div class="explain"><b>${ok ? t('correct') : t('wrong')}</b> ${esc(q.e)}</div>
        <div class="row mt" style="justify-content:flex-end"><button class="btn" data-next>${last ? t('check') : t('next')}</button></div>`;
    } else if (nx && quiz) { quiz.i++; renderQuiz(); }
  }

