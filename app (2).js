  function initSearch() {
    const inp = $('#searchInput'), res = $('#searchResults');
    inp.addEventListener('input', () => {
      const q = inp.value.trim().toLowerCase();
      if (q.length < 2) { res.hidden = true; return; }
      const hits = LESSONS.filter(l => l.topic.toLowerCase().includes(q)).slice(0, 8);
      res.innerHTML = hits.length
        ? hits.map(l => `<a href="#/lesson/${l.id}"><span>${esc(l.topic)}</span><small>${l.sem}-${t('sem')} · №${l.n}</small></a>`).join('')
        : `<div style="padding:12px 14px" class="muted">${t('nothing')}</div>`;
      res.hidden = false;
    });
    document.addEventListener('click', e => {
      if (!e.target.closest('.search')) res.hidden = true;
      else if (e.target.closest('a')) { res.hidden = true; inp.value = ''; }
    });
  }

